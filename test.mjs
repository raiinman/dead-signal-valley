import assert from 'node:assert/strict';
import {destinations,bridgeHeight,isBlocked,moveBody,loadJournal} from './dist/simulation.js';
assert.equal(Object.keys(destinations).length,10);
assert.equal(bridgeHeight(0,-16),.55);
assert.equal(bridgeHeight(3,-16),null);
assert.equal(bridgeHeight(0,-10),0);
assert.equal(bridgeHeight(0,-22),0);
assert(Math.abs(bridgeHeight(0,-10.75)-.275)<1e-8);
const wall={x:0,z:0,w:1,d:10,minY:0,maxY:3};
const b={x:-2,z:0,feet:0};
moveBody(b,5,2,[wall],()=>0);
assert(b.x<-.77,'substeps prevent walking through thin walls');
assert(b.z>1.9,'wall collision still allows sliding');
assert(!isBlocked(0,0,4,[wall]),'flight clears low walls');
const shore={x:0,z:0,feet:0}; moveBody(shore,0,-2,[],(x,z)=>z<-.5?null:0); assert(shore.z>=-.5,'water boundary blocks walking');
const step={x:0,z:0,feet:0};moveBody(step,1,0,[],x=>x>.5?1:0);assert(step.x<=.5,'cannot step through a one-metre wall');
assert.deepEqual([...loadJournal({getItem:()=>'{bad'})],[]);
assert.deepEqual([...loadJournal({getItem:()=>'["cafe","bogus","plaza"]'})],['cafe','plaza']);
assert.deepEqual([...loadJournal({getItem:()=>'null'})],[]);
assert.deepEqual([...loadJournal({getItem:()=>'["cafe","plaza","bridge","station"]'})],['cafe','plaza','bridge','station'],'existing visitor notes survive town expansion');
console.log('PASS: bridge ramps, collision sliding and tunnelling, water boundaries, step height and journal recovery.');
